#!/usr/bin/env node
/**
 * Publish the V3 package folders to the existing package-images bucket (DEV).
 *
 * Same bucket and same storage client the runtime already uses; this only adds
 * a predictable prefix so one folder exists per package, variant and locale.
 * Writes the resulting map to Lib/publicQuote/packageFolderArt.generated.ts so
 * the app resolves art without a second image infrastructure.
 *
 * V3 goes to its own prefix and the V2 objects are left in place, so rolling
 * back is a matter of pointing the prefix at the old set again.
 *
 *   node scripts/dev/upload-cdl-package-folders-v3.mjs
 */
import { createClient } from '@supabase/supabase-js'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SOURCE_DIR = join(ROOT, 'assets/packages/folders-v3')
const BUCKET = 'package-images'
const PREFIX = 'cdl-folders-v3'
const DEV_REF = 'yasprgtlqclwsjcshtls'

const url = process.env.NEXT_PUBLIC_SUPABASE_URL
const key = process.env.SUPABASE_SERVICE_ROLE_KEY
if (!url || !key) {
  console.error('NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required')
  process.exit(1)
}
const ref = new URL(url).hostname.split('.')[0]
if (ref !== DEV_REF) {
  console.error(`BLOCKED: expected the DEV project ${DEV_REF}, got ${ref}`)
  process.exit(1)
}

const supabase = createClient(url, key, { auth: { persistSession: false } })

/** bbqtrad-plus-pt-v3.webp -> { key: 'BBQTRAD+', locale: 'pt' } */
function parseName(file) {
  const m = /^([a-z]+)(-plus)?-(pt|en|es)-v3\.webp$/.exec(file)
  if (!m) return null
  return { key: `${m[1].toUpperCase()}${m[2] ? '+' : ''}`, locale: m[3] }
}

const files = readdirSync(SOURCE_DIR).filter((f) => f.endsWith('.webp')).sort()
const map = {}
let uploaded = 0

for (const file of files) {
  const parsed = parseName(file)
  if (!parsed) {
    console.warn(`skip ${file}: unexpected name`)
    continue
  }
  const body = readFileSync(join(SOURCE_DIR, file))
  const path = `${PREFIX}/${file}`
  const { error } = await supabase.storage.from(BUCKET).upload(path, body, {
    contentType: 'image/webp',
    upsert: true,
    cacheControl: '31536000',
  })
  if (error) {
    console.error(`FAIL ${path}: ${error.message}`)
    process.exit(1)
  }
  map[parsed.key] ??= {}
  // Store the storage path, not the full URL: the host belongs to the
  // environment, and the map should stay portable between projects.
  map[parsed.key][parsed.locale] = file
  uploaded += 1
  console.log(`ok ${parsed.key} ${parsed.locale} -> ${path}`)
}

const generated = `/**
 * Generated by scripts/dev/upload-cdl-package-folders-v3.mjs — do not edit.
 *
 * One folder per package, variant and locale. Values are file names inside
 * \`${BUCKET}/${PREFIX}\`, the bucket the runtime already reads from; the host
 * comes from the environment so this map is portable.
 */
export const PACKAGE_FOLDER_BUCKET = '${BUCKET}'
export const PACKAGE_FOLDER_PREFIX = '${PREFIX}'

export const PACKAGE_FOLDER_ART_V2: Record<
  string,
  Partial<Record<'pt' | 'en' | 'es', string>>
> = ${JSON.stringify(map, null, 2)}
`
writeFileSync(join(ROOT, 'Lib/publicQuote/packageFolderArt.generated.ts'), generated)
console.log(`\nuploaded ${uploaded} folders for ${Object.keys(map).length} packages`)
