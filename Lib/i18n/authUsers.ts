export type AuthMessageKey = keyof (typeof dict)['pt']

export function tAuth(locale: AuthLocale | string | null | undefined, key: AuthMessageKey): string {
  const loc: AuthLocale =
    locale === 'en' || locale === 'es' || locale === 'pt' ? locale : 'pt'
  return dict[loc][key]
}

export function resolveAuthLocale(
  value: string | null | undefined,
): AuthLocale {
  if (!value) return 'pt'
  const v = value.toLowerCase()
  if (v.startsWith('en')) return 'en'
  if (v.startsWith('es')) return 'es'
  return 'pt'
}
