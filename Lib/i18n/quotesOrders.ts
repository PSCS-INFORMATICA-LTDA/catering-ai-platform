export type QuotesOrdersMessageKey = keyof (typeof dict)['pt']

export function tQuotesOrders(
  locale: AuthLocale | string | null | undefined,
  key: QuotesOrdersMessageKey,
): string {
  const loc: AuthLocale =
    locale === 'en' || locale === 'es' || locale === 'pt' ? locale : 'pt'
  return dict[loc][key]
}

const QUOTE_STATUS_KEY_MAP: Record<string, QuotesOrdersMessageKey> = {
  draft: 'quoteStatusDraft',
  ready_for_review: 'quoteStatusReadyForReview',
  sent: 'quoteStatusSent',
  viewed: 'quoteStatusViewed',
  accepted: 'quoteStatusAccepted',
  approved: 'quoteStatusAccepted',
  converted: 'quoteStatusConverted',
  rejected: 'quoteStatusRejected',
  expired: 'quoteStatusExpired',
  cancelled: 'quoteStatusCancelled',
  canceled: 'quoteStatusCancelled',
  archived: 'quoteStatusArchived',
}

export function quoteStatusLabel(
  status: string | null | undefined,
  locale: AuthLocale | string | null | undefined = 'pt',
): string {
  const key = QUOTE_STATUS_KEY_MAP[(status ?? '').trim().toLowerCase()]
  if (!key) return status ?? '—'
  return tQuotesOrders(locale, key)
}

